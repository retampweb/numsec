"""Turn scan findings into assistant-friendly threat artefacts.

``numsec analyze`` writes one directory per threat under ``numsec/threats/``. Two
properties matter more than anything else here:

* **Regeneration is safe.** Every file we write starts with a marker comment, and a
  re-run only deletes directories that carry it. Hand-written threats and notes in
  the same tree are left alone.
* **We never echo the secret itself.** Excerpts for credential rules are redacted,
  because ``threat.md`` is committed to the repository — leaking the key into the
  report would be a fresh incident.
"""

from __future__ import annotations

import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from .detect import DEFAULT_RULES, Finding, Rule, ScanResult, Severity, scan_project

GENERATED_MARKER = "<!-- generated by numsec"

_REDACTED_RULES = frozenset({"hardcoded-secret", "aws-access-key", "github-token", "slack-token"})

_QUOTED_LITERAL = re.compile(r"""(["'])(?:(?!\1).){4,}\1""")
_AWS_KEY = re.compile(r"\b(?:AKIA|ASIA)[0-9A-Z]{16}\b")
_GITHUB_TOKEN = re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{22,})\b")
_SLACK_TOKEN = re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b")

THREATS_README = """# Threats

Every `THREAT-*/threat.md` in this directory was produced by `numsec analyze`.

- Re-run `numsec analyze --ai-format` to refresh the generated files.
- Files carrying the `generated by numsec` marker are overwritten; anything else here
  is yours and will never be touched.
- Ask your assistant to turn a threat into a change proposal under `numsec/changes/`.
"""


@dataclass(frozen=True)
class Threat:
    """A group of findings that share one rule."""

    threat_id: str
    rule_id: str
    title: str
    stride: str
    severity: Severity
    occurrences: tuple[Finding, ...]
    attack_scenario: str
    impact: str
    remediation: tuple[str, ...]

    @property
    def relative_dir(self) -> Path:
        return Path("numsec") / "threats" / self.threat_id


@dataclass(frozen=True)
class AnalysisResult:
    """What ``analyze`` did, in a shape the CLI can render."""

    project_root: Path
    threats_dir: Path
    scan: ScanResult
    threats: tuple[Threat, ...]
    generated: tuple[Path, ...]
    removed: tuple[str, ...]
    preserved: tuple[str, ...]

    @property
    def max_severity(self) -> Severity | None:
        return self.scan.max_severity

    def to_dict(self) -> dict[str, object]:
        return {
            "status": "ok",
            "mode": "static-rules",
            "project_root": str(self.project_root),
            "threats_dir": str(self.threats_dir),
            "files_scanned": self.scan.files_scanned,
            "findings": len(self.scan.findings),
            "max_severity": self.max_severity.value if self.max_severity else None,
            "generated": [str(path) for path in self.generated],
            "removed": list(self.removed),
            "preserved": list(self.preserved),
            "threats": [
                {
                    "threat_id": threat.threat_id,
                    "rule": threat.rule_id,
                    "title": threat.title,
                    "stride": threat.stride,
                    "severity": threat.severity.value,
                    "occurrences": [
                        {"location": finding.location, "excerpt": redact(finding)}
                        for finding in threat.occurrences
                    ],
                }
                for threat in self.threats
            ],
        }


def redact(finding: Finding) -> str:
    """Mask credential-shaped fragments before they land in a committed file."""
    if finding.rule.id not in _REDACTED_RULES:
        return finding.excerpt
    text = _QUOTED_LITERAL.sub(r"\1***\1", finding.excerpt)
    text = _AWS_KEY.sub("AKIA***", text)
    text = _GITHUB_TOKEN.sub("gh_***", text)
    return _SLACK_TOKEN.sub("xox-***", text)


def group_findings(findings: tuple[Finding, ...]) -> list[tuple[Rule, list[Finding]]]:
    """Group findings by rule, most severe rule first."""
    grouped: dict[str, tuple[Rule, list[Finding]]] = {}
    for finding in findings:
        entry = grouped.setdefault(finding.rule.id, (finding.rule, []))
        entry[1].append(finding)
    return sorted(
        grouped.values(),
        key=lambda entry: (-entry[0].severity.rank, entry[0].id),
    )


def build_threats(findings: tuple[Finding, ...]) -> tuple[Threat, ...]:
    """Assign stable, human-friendly identifiers (THREAT-001, ...)."""
    threats: list[Threat] = []
    for index, (rule, rule_findings) in enumerate(group_findings(findings), start=1):
        threats.append(
            Threat(
                threat_id=f"THREAT-{index:03d}",
                rule_id=rule.id,
                title=rule.title,
                stride=rule.stride,
                severity=rule.severity,
                occurrences=tuple(rule_findings),
                attack_scenario=rule.attack_scenario,
                impact=rule.impact,
                remediation=rule.remediation,
            )
        )
    return tuple(threats)


def render_threat_md(threat: Threat) -> str:
    """Render one threat as markdown (§-stable, diff-friendly, assistant-friendly)."""
    occurrences = "\n".join(
        f"- `{finding.location}` — {redact(finding)}" for finding in threat.occurrences
    )
    remediation = "\n".join(f"- {step}" for step in threat.remediation)
    return (
        f"{GENERATED_MARKER}; threat-id: {threat.threat_id}; rule: {threat.rule_id} -->\n"
        f"<!-- severity: {threat.severity.value} -->\n\n"
        f"# {threat.title}\n\n"
        f"- **Threat ID**: `{threat.threat_id}`\n"
        f"- **STRIDE**: **{threat.stride}**\n"
        f"- **Severity**: **{threat.severity.value.upper()}**\n"
        f"- **Rule**: `{threat.rule_id}`\n"
        f"- **Occurrences**: {len(threat.occurrences)}\n\n"
        f"## Affected files/components\n\n"
        f"{occurrences}\n\n"
        f"## Attack scenario\n\n"
        f"{threat.attack_scenario}\n\n"
        f"## Impact\n\n"
        f"{threat.impact}\n\n"
        f"## Recommended remediation\n\n"
        f"{remediation}\n"
    )


def _prune_generated(threats_dir: Path) -> tuple[list[str], list[str]]:
    """Delete only directories we generated ourselves; report what was kept."""
    removed: list[str] = []
    preserved: list[str] = []
    for child in sorted(threats_dir.iterdir()):
        if not child.is_dir() or not child.name.startswith("THREAT-"):
            continue
        threat_md = child / "threat.md"
        if not threat_md.is_file():
            preserved.append(child.name)
            continue
        try:
            head = threat_md.read_text(encoding="utf-8", errors="replace")[:200]
        except OSError:
            preserved.append(child.name)
            continue
        if GENERATED_MARKER in head:
            shutil.rmtree(child, ignore_errors=True)
            removed.append(child.name)
        else:
            preserved.append(child.name)
    return removed, preserved


def analyze_project(
    project_root: Path,
    *,
    write: bool = True,
) -> AnalysisResult:
    """Scan ``project_root`` and (optionally) write ``numsec/threats`` artefacts."""
    root = project_root.resolve()
    if not root.is_dir():
        raise NotADirectoryError(f"Not a directory: {root}")

    threats_dir = root / "numsec" / "threats"
    scan = scan_project(root, DEFAULT_RULES)

    # Generated artefacts must not become scan input.
    findings = tuple(
        finding
        for finding in scan.findings
        if finding.path.parts[:2] != ("numsec", "threats")
    )
    scan = ScanResult(findings=findings, files_scanned=scan.files_scanned)
    threats = build_threats(findings)

    removed: list[str] = []
    preserved: list[str] = []
    generated: list[Path] = []

    if write:
        threats_dir.mkdir(parents=True, exist_ok=True)
        removed, preserved = _prune_generated(threats_dir)

        readme = threats_dir / "README.md"
        if not readme.exists():
            readme.write_text(THREATS_README, encoding="utf-8")

        for threat in threats:
            target = root / threat.relative_dir / "threat.md"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(render_threat_md(threat), encoding="utf-8")
            generated.append(target.relative_to(root))

    return AnalysisResult(
        project_root=root,
        threats_dir=threats_dir,
        scan=scan,
        threats=threats,
        generated=tuple(generated),
        removed=tuple(removed),
        preserved=tuple(preserved),
    )
